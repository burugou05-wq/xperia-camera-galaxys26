"""Fit a conservative, opt-in sRGB chart transfer, not a camera calibration."""
from pathlib import Path
import sys, json, hashlib
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools/pydeps'))
import numpy as np
from PIL import Image
folder=ROOT/'analysis/color-reference'

def patches(name):
    image=np.asarray(Image.open(folder/f'{name}-chart.jpg').convert('RGB'),dtype=float)/255
    h,w,_=image.shape
    values=[]
    for row in range(4):
        for col in range(6):
            x,y=round((col+.5)*w/6),round((row+.5)*h/4)
            values.append(np.median(image[y-12:y+12,x-12:x+12].reshape(-1,3),axis=0))
    return np.array(values)

def linear(x): return np.where(x<=.04045,x/12.92,((x+.055)/1.055)**2.4)
def srgb(x):
    x=np.clip(x,0,1)
    return np.where(x<=.0031308,x*12.92,1.055*x**(1/2.4)-.055)

source,target=patches('galaxy'),patches('xperia')
X=linear(source)
Y=linear(target)
prior=np.eye(3)
def fit(x,y,ridge):
    penalty=np.eye(3)*ridge
    return np.linalg.solve(x.T@x+penalty,x.T@y+penalty@prior)
def rmse(a,b): return float(np.sqrt(np.mean((a-b)**2))*255)
candidates=[]
for ridge in [.001,.003,.01,.03,.1,.3,1,3]:
    predictions=[]
    for i in range(24):
        keep=np.arange(24)!=i
        predictions.append(srgb(X[i]@fit(X[keep],Y[keep],ridge)))
    candidates.append((rmse(np.array(predictions),target),ridge))
score,ridge=min(candidates)
coefficients=fit(X,Y,ridge).T
report={
 'description':'Experimental transfer between two published camera chart JPEGs. Not SC-51G calibration or Sony ISP reproduction.',
 'sources':{
  'galaxy':{'page':'https://www.notebookcheck.net/Exynos-and-more-battery-power-make-it-a-star-Samsung-Galaxy-S26-review.1284566.0.html','model':'Galaxy S26 Exynos, stock camera','image':'https://www.notebookcheck.net/fileadmin/_processed_/8/6/csm_Photo_GalaxyS26_ColorChecker_60f42351ef.jpg'},
  'xperia':{'page':'https://www.notebookcheck.pl/Recenzja-Sony-Xperia-1-VII-wymarzony-smartfon-dla-tworcow-tresci-i-entuzjastow-fotografii.1122762.0.html','model':'Xperia 1 VII, stock camera','image':'https://www.notebookcheck.net/fileadmin/_processed_/5/8/csm_Photo_Xperia1_ColorChecker_3570738a6b.jpg'}},
 'patch_sampling':'24 patch medians, central 24x24 pixels; published bright-light charts',
 'source_rgb':source.tolist(),'target_rgb':target.tolist(),
 'linear_rgb_matrix_3x3':coefficients.tolist(),'ridge':ridge,
 'baseline_rgb_rmse_8bit':rmse(source,target),
 'leave_one_patch_out_rgb_rmse_8bit':score,
 'training_rgb_rmse_8bit':rmse(srgb(X@coefficients.T),target),
 'limitations':['Different review dates, firmware and hardware','Reference Galaxy is Exynos, target SC-51G is Snapdragon','Published resized JPEGs; no raw spectral calibration','Stock-camera results differ from this port','Validation only across chart patches; no held-out scene validation'],
 'sha256':{n:hashlib.sha256((folder/f'{n}-chart.jpg').read_bytes()).hexdigest() for n in ['galaxy','xperia']}}
(folder/'fit-report.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
java='package local.sc51g;\n\n/** Generated by tools/fit-color-reference.py; experimental web-chart transfer. */\npublic final class ColorReference {\n    public static final float[] MATRIX = {\n'
java+='\n'.join('        '+', '.join(f'{v:.9f}f' for v in row)+',' for row in coefficients)
java+='\n    };\n}\n'
(ROOT/'src/local/sc51g/ColorReference.java').write_text(java,encoding='utf-8')
print(json.dumps({k:report[k] for k in ['ridge','baseline_rgb_rmse_8bit','leave_one_patch_out_rgb_rmse_8bit','training_rgb_rmse_8bit','linear_rgb_matrix_3x3']},indent=2))
